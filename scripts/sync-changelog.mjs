// Canonical sync-changelog for @rtorcato/* docs sites (shipped by
// @rtorcato/repo-tooling — copy via `repo-tooling copy docusaurus-sync-changelog`).
//
// Builds the docs site's changelog page from **GitHub Releases**, not from
// CHANGELOG.md. The output file is gitignored — it is regenerated on every docs
// build (wire it into the docs app's `build`/`start` scripts; pnpm 8 doesn't run
// `pre*` hooks reliably, so chain it explicitly).
//
// Why Releases and not the file: the shipped semantic-release github preset
// does not use @semantic-release/git, because the `code-scanning-main` ruleset
// rejects the release commit with GH013 (see tooling/semantic-release/github.mjs
// and rtorcato/repo-tooling#417). Nothing commits CHANGELOG.md back, so it is
// frozen at whatever the last release with that plugin wrote — and it freezes at
// a *real* release, which is why it reads as current. @semantic-release/github
// writes Releases from the same notes that used to build CHANGELOG.md, so
// concatenating their bodies reproduces the old page and cannot go stale.
//
// The target defaults to Docusaurus's `apps/docs/docs/changelog.md`. Override
// with the CHANGELOG_TARGET env var (path relative to the repo root) for other
// layouts — e.g. a Fumadocs content root:
//   CHANGELOG_TARGET=apps/web/content/docs/changelog.mdx node scripts/sync-changelog.mjs
// The title/description frontmatter is framework-neutral (both Docusaurus and
// Fumadocs read it), so only the path changes between frameworks.
//
// The docs workflow must rebuild on `release: types: [published]` — with no
// release commit landing on the default branch, a `push` trigger never fires.

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const repoRoot = resolve(here, '..')
const target = resolve(repoRoot, process.env.CHANGELOG_TARGET ?? 'apps/docs/docs/changelog.md')

/** `owner/name` — from CI, else from package.json `repository`. */
function resolveRepo() {
	if (process.env.GITHUB_REPOSITORY) return process.env.GITHUB_REPOSITORY
	const pkg = JSON.parse(readFileSync(resolve(repoRoot, 'package.json'), 'utf8'))
	const url = typeof pkg.repository === 'string' ? pkg.repository : pkg.repository?.url
	const match = /github\.com[/:]([^/]+\/[^/.]+)/.exec(url ?? '')
	if (!match) throw new Error('no GITHUB_REPOSITORY and no github repository in package.json')
	return match[1]
}

const frontmatter = `---
title: Changelog
description: Release notes, generated by semantic-release and published to GitHub Releases.
---

`

const footer = (repo, note) =>
	`\n\n---\n\n${note}Every entry above is generated by semantic-release and published to [GitHub Releases](https://github.com/${repo}/releases). Anything older than the first GitHub Release is recorded in [CHANGELOG.md](https://github.com/${repo}/blob/main/CHANGELOG.md).\n`

async function fetchReleases(repo) {
	const headers = { Accept: 'application/vnd.github+json' }
	// Optional: lifts the 60/hr unauthenticated rate limit. CI passes it; local
	// builds work fine without it at a typical repo's release count.
	// ponytail: one page of 100. Paginate when a repo outgrows it.
	const token = process.env.GITHUB_TOKEN ?? process.env.GH_TOKEN
	if (token) headers.Authorization = `Bearer ${token}`

	const res = await fetch(`https://api.github.com/repos/${repo}/releases?per_page=100`, { headers })
	if (!res.ok) throw new Error(`GitHub API ${res.status} ${res.statusText}`)
	return res.json()
}

function render(releases) {
	// The API does not guarantee date order, and a release body already carries
	// its own version heading and date — so sort here and emit bodies verbatim.
	const sorted = releases
		.filter((r) => !r.draft && r.body?.trim())
		.sort((a, b) => new Date(b.published_at) - new Date(a.published_at))

	if (sorted.length === 0) throw new Error('no releases with a body')
	return sorted.map((r) => r.body.trim()).join('\n\n')
}

let repo = ''
let body
try {
	repo = resolveRepo()
	body = render(await fetchReleases(repo)) + footer(repo, '')
	console.log(`sync-changelog: built from ${repo} GitHub Releases`)
} catch (error) {
	// Never fail the docs build on a network blip — fall back to the frozen file
	// and say so on the page rather than shipping a silently truncated one.
	console.warn(`sync-changelog: ${error.message} — falling back to CHANGELOG.md`)
	try {
		body =
			readFileSync(resolve(repoRoot, 'CHANGELOG.md'), 'utf8').trim() +
			(repo
				? footer(
						repo,
						'**This page was built from the repository CHANGELOG.md because GitHub Releases could not be reached, and may be out of date.** '
					)
				: '')
	} catch {
		body = '# Changelog\n\nNo releases recorded yet.\n'
	}
}

mkdirSync(dirname(target), { recursive: true })
writeFileSync(target, frontmatter + body)
console.log(`sync-changelog: wrote ${target}`)
